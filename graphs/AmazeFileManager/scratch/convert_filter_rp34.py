#!/usr/bin/env python3
import json
import re

# Load method list
with open('/Users/darshan/Desktop/yang/work/graphs/AmazeFileManager/method_list.json') as f:
    methods = set(m['short'] for m in json.load(f))

# Read repair_rp34.py and extract edges
edges = []
unreachable = []

with open('/Users/darshan/Desktop/yang/work/graphs/AmazeFileManager/parts/repair_rp34.py') as f:
    content = f.read()
    
# Find EDGES.append(...) patterns
edge_pattern = r"EDGES\.append\(edge\(\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']*)',\s*'([^']*)'\s*\)\)"
for match in re.finditer(edge_pattern, content, re.MULTILINE | re.DOTALL):
    src, dst, kind, summary, evidence = match.groups()
    edges.append((src, dst, kind, summary, evidence))

# Find UNREACHABLE entries
unreachable_pattern = r"UNREACHABLE\['([^']+)'\] = \(\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']+)'\s*\)"
for match in re.finditer(unreachable_pattern, content, re.MULTILINE | re.DOTALL):
    method, kind, reason, src_line, confirmed_by = match.groups()
    unreachable.append((method, kind, reason, src_line, confirmed_by))

print(f"Found {len(edges)} edges and {len(unreachable)} UNREACHABLE entries")

# Filter edges to only keep those where both src and dst exist
kept_edges = []
dropped_edges = []
for src, dst, kind, summary, evidence in edges:
    if src in methods and dst in methods:
        kept_edges.append((src, dst, kind, summary, evidence))
    else:
        dropped_edges.append((src, dst))
        
print(f"Keeping {len(kept_edges)}/{len(edges)} edges")
print(f"Dropped {len(dropped_edges)} edges to non-existent nodes")

# Write converted file
with open('/Users/darshan/Desktop/yang/work/graphs/AmazeFileManager/parts/repair_rp34_filtered.py', 'w') as f:
    f.write("# Repair batch 34: Extra round 1 (converted from EDGES list format and filtered)\n")
    f.write("# Generated by convert_filter_rp34.py\n\n")
    
    # Write kept edges
    for src, dst, kind, summary, evidence in kept_edges:
        # Escape evidence string
        evidence_escaped = evidence.replace("'", "\\'").replace('\n', ' ')
        f.write(f"e('{src}', '{dst}', '{kind}',\n")
        f.write(f"  '{summary}',\n")
        f.write(f"  evidence='{evidence_escaped}')\n\n")
    
    # Write all UNREACHABLE entries (these don't add edges, so they're safe)
    for method, kind, reason, src_line, confirmed_by in unreachable:
        reason_escaped = reason.replace("'", "\\'")
        src_line_escaped = src_line.replace("'", "\\'")
        f.write(f"UNREACHABLE['{method}'] = (\n")
        f.write(f"    '{kind}',\n")
        f.write(f"    '{reason_escaped}',\n")
        f.write(f"    '{src_line_escaped}',\n")
        f.write(f"    '{confirmed_by}'\n")
        f.write(")\n\n")

for src, dst in dropped_edges[:10]:
    print(f"  {src} -> {dst}")
if len(dropped_edges) > 10:
    print(f"  ... and {len(dropped_edges) - 10} more")
