def ln(path, pat):
    lines = open(path, encoding='utf-8', errors='replace').read().split('\n')
    hits = [i + 1 for i, l in enumerate(lines) if re.search(pat, l)]
    if not hits:
        raise SystemExit('no line: %s %s' % (path, pat))
    return hits[0]

def src(rel, pat):
    return ln(os.path.join(SRCROOT, rel), pat)

def find(name):
    for dp, dn, fn in os.walk(SRCROOT):
        if name in fn:
            return os.path.relpath(os.path.join(dp, name), SRCROOT)
    raise SystemExit('no file ' + name)

