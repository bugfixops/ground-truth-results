# Pass generator for section L part 2. Appends one marked block to graph_def.py.
# usage (from work/):  python3 graphs/AnyMemo/scratch/gen_L2.py PASS      (refuses to run twice for the same PASS)
import json, re, os, sys, collections
BASE = '/Users/darshan/Desktop/yang/work/graphs/AnyMemo'
SRCROOT = '/Users/darshan/Desktop/yang/final_java_only/AnyMemo/app/AnyMemo-#10.12.2/app/src/main/java/org/liberty/android/fantastischmemo'
RESROOT = os.path.join(os.path.dirname(os.path.dirname(SRCROOT)), 'res')
PASS = int(sys.argv[1])
GDEF = BASE + '/graph_def.py'
HDR = '# ---- section L part 2, pass %d (generated by scratch/gen_L2.py; do not edit by hand) ----' % PASS
txt = open(GDEF, encoding='utf-8').read()
if HDR in txt:
    if '--regen' not in sys.argv: sys.exit('pass %d already in graph_def.py (use --regen)' % PASS)
    txt = txt[:txt.find('\n' + HDR)] + '\n'
    open(GDEF, 'w', encoding='utf-8').write(txt)
G = json.load(open(BASE + '/out/anymemo_trigger_graph.json'))
V = G['verdict']; E = G['edges']

def base(k): return k.split('(')[0]
def split_key(k):
    c, _, n = base(k).rpartition('.')
    return c, n

CALLBACK = set('''onClick onLongClick onItemClick onItemLongClick onItemSelected onNothingSelected onCheckedChanged onCancel onDismiss onShow
onCreateLoader onLoadFinished onLoaderReset onTouch onKey onFocusChange onEditorAction onTextChanged beforeTextChanged afterTextChanged
onPreferenceClick onPreferenceChange onCreateActionMode onPrepareActionMode onActionItemClicked onDestroyActionMode onInit
onUtteranceCompleted onCompletion onPageFinished handleTag compare call onGesturePerformed onServiceConnected onServiceDisconnected
onReceive onGetViewFactory getViewAt getCount getItemId getView getItem'''.split())
LIBISH = CALLBACK | set('''toString equals hashCode run finalize clone close uncaughtException doInBackground onPreExecute onPostExecute
onProgressUpdate startElement endElement characters startDocument endDocument setDocumentLocator write read transition
onRequestPermissionsResult'''.split())
# names that some XML attribute calls (android:onClick="...") -- these are framework-dispatched, never U
XML_NAMES = set()
for dp, dn, fn in os.walk(RESROOT):
    for f in fn:
        if f.endswith('.xml'):
            XML_NAMES |= set(re.findall(r'android:\w+="(\w+)"', open(os.path.join(dp, f), encoding='utf-8', errors='replace').read()))
RULES = [('DialogInterface', 'FW_DIALOGFRAG'), ('AlertDialog', 'FW_DIALOGFRAG'), ('ActionMode', 'FW_ACTIONMODE'),
         ('LoaderCallbacks', 'FW_LOADER'), ('Comparator', 'FW_SORT'), ('Callable', 'FW_RX'), ('Observable', 'FW_RX'),
         ('Consumer', 'FW_RX'), ('ServiceConnection', 'FW_SERVICECONN'), ('OnInitListener', 'FW_TTS'),
         ('UtteranceProgressListener', 'FW_TTS'), ('OnCompletionListener', 'FW_MEDIAPLAYER'),
         ('OnPreferenceClickListener', 'FW_PREFERENCE'), ('OnPreferenceChangeListener', 'FW_PREFERENCE'),
         ('WebViewClient', 'FW_WEBVIEW'), ('GestureOverlayView', 'FW_GESTURE'), ('TagHandler', 'FW_TAG'),
         ('OnClickListener', 'FW_VIEW'), ('OnLongClickListener', 'FW_VIEW'), ('OnTouchListener', 'FW_VIEW'),
         ('OnItemClickListener', 'FW_VIEW'), ('OnItemSelectedListener', 'FW_VIEW'), ('OnCheckedChangeListener', 'FW_VIEW'),
         ('OnEditorActionListener', 'FW_VIEW'), ('OnFocusChangeListener', 'FW_VIEW'), ('OnKeyListener', 'FW_VIEW'),
         ('TextWatcher', 'FW_VIEW'), ('BroadcastReceiver', 'FW_RECEIVER')]

BYNAME = collections.defaultdict(list)
for dp, dn, fn in os.walk(SRCROOT):
    for f in fn:
        if f.endswith('.java'): BYNAME[f].append(os.path.join(dp, f))
def resolve(rf):
    """return (abs_path, rel_path) for an SRC citation that may be only a basename"""
    p = os.path.join(SRCROOT, rf)
    if os.path.exists(p): return p, os.path.relpath(p, SRCROOT)
    c = BYNAME.get(os.path.basename(rf), [])
    c = [x for x in c if x.endswith(rf)] or c
    if len(c) != 1: raise SystemExit('ambiguous or missing source for citation: %s %r' % (rf, c))
    return c[0], os.path.relpath(c[0], SRCROOT)

DECL = {}
for dp, dn, fn in os.walk(SRCROOT):
    for f in fn:
        if f.endswith('.java'):
            s = open(os.path.join(dp, f), encoding='utf-8', errors='replace').read()
            for mm in re.finditer(r'\b(?:class|interface|enum)\s+(\w+)\b([^{]*)\{', s):
                DECL.setdefault(mm.group(1), mm.group(2))
def has_lib(name, depth=0):
    """True if the class, or an app ancestor of it, extends/implements a type that is not declared in the app"""
    if depth > 10 or name not in DECL: return name not in DECL
    for w in re.findall(r'\b([A-Z]\w*)', DECL[name]):
        if w == name: continue
        if w not in DECL or has_lib(w, depth + 1): return True
    return False
def fam_text(f, line):
    L = open(f, encoding='utf-8', errors='replace').read().split('\n')
    t = ' '.join(L[max(0, line - 4): line])
    for pat, fam in RULES:
        if pat in t: return fam
    return None

# creators: class key -> [(src, relfile, line)] from any edge into Class.<init>
ctor = collections.defaultdict(list)
inc = collections.Counter()
for x in E:
    if x['kind'] != 'REGISTER': inc[x['dst']] += 1
    b = base(x['dst'])
    if b.endswith('.<init>'):
        m = re.search(r'SRC ([^\s;]+?\.java):(\d+)', x.get('evidence') or '')
        if m: ctor[b[:-len('.<init>')]].append((x['src'], m.group(1), int(m.group(2))))

UNRES = sorted(m for m, v in V.items() if v == 'UNRESOLVED')
F, U, skipped = [], [], collections.Counter()
used_fw = set()
for m in UNRES:
    cls, name = split_key(m)
    if name in CALLBACK:
        pick = None
        for src, rf, line in ctor.get(cls, []):
            if V.get(src) != 'REACHABLE': continue
            ap, rp = resolve(rf)
            fam = fam_text(ap, line)
            if fam: pick = (src, rp, line, fam); break
        if pick:
            src, rf, line, fam = pick
            F.append("e(%r, %r, 'FRAMEWORK', %r, evidence=%s + %r)" % (src, m, 'framework calls %s on the object created at %s:%d' % (name, rf, line),
                     fam, '; SRC %s:%d' % (rf, line)))
            used_fw.add(m)
        else:
            skipped['callback, no REACHABLE creator with a known family'] += 1
        continue
    if inc[m] > 0: skipped['has incoming edges (chained, later pass)'] += 1; continue
    if name.startswith('<'): skipped['clinit / init (later pass)'] += 1; continue
    if name == '<init>': skipped['constructor with zero callers (later pass)'] += 1; continue
    if name.startswith('on') or name in LIBISH or name in XML_NAMES: skipped['framework-named method (later pass)'] += 1; continue
    top = cls.split('$')[0].split('.')[-1]
    cand = BYNAME.get(top + '.java', [])
    if len(cand) != 1: skipped['no app source file (library or generated class)'] += 1; continue
    f = cand[0]
    # declaration line: the first line of the file that declares the method name
    simple = name
    pat = re.compile(r'^\s*(?:(?:public|private|protected|static|final|synchronized|abstract|default)\s+)*(?:<[^>]+>\s+)?[\w.<>\[\],?]+\s+' + re.escape(simple) + r'\s*\(')
    L = open(f, encoding='utf-8', errors='replace').read().split('\n')
    hit = None
    for i, t in enumerate(L):
        if pat.search(t) and not t.strip().startswith(('return', '//', '*')):
            hit = i + 1; break
    if not hit: skipped['declaration line not found'] += 1; continue
    rf = os.path.relpath(f, SRCROOT)
    if re.search(r'\$\d+$', cls) or re.search(r'\$\d+\$', cls): skipped['anonymous/local class (callback; later pass)'] += 1; continue
    if rf.startswith('modules/'): skipped['Dagger @Provides module (generated component call; later pass)'] += 1; continue
    if rf.startswith('dao/') or top.endswith('DaoImpl'): skipped['DAO method (ORMLite Dao dispatch; later pass)'] += 1; continue
    simple = cls.split('$')[-1]
    src_txt = open(f, encoding='utf-8', errors='replace').read()
    hm = re.search(r'\bclass\s+' + re.escape(simple) + r'\b([^{]*)\{', src_txt)
    clause = hm.group(1) if hm else ''
    if has_lib(simple): skipped['class extends/implements a library type (framework may call it; later pass)'] += 1; continue
    U.append((m, rf, hit))

out = []
out.append('')
out.append(HDR)
for line in F: out.append(line)
for m, rf, hit in U:
    out.append("UNREACHABLE[%r] = ('no_trigger_in_app', %r, %r, 'SOURCE')" % (m,
        'no call of this method in the app (bytecode: no invoke site; declaration only)', 'SRC %s:%d' % (rf, hit)))
out.append('# ---- end pass %d ----' % PASS)
open(GDEF, 'a', encoding='utf-8').write('\n'.join(out) + '\n')
print('pass', PASS, 'framework edges', len(F), 'unreachable', len(U))
for k, v in skipped.most_common(): print('  skipped:', v, k)
print('sample U:')
for m, rf, hit in U[:5]:
    print('  ', m, rf, hit, '|', open(os.path.join(SRCROOT, rf), encoding='utf-8', errors='replace').read().split('\n')[hit - 1].strip()[:90])
