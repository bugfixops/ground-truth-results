# Writes section H (UNREACHABLE literal + SUPPRESS pairs) at the end of graph_def.py.
# Idempotent: everything from the section H marker line to the end of the file is replaced on each run.
# Inputs: scratch/dead_plan.json (node -> [kind, reason, source_ref, confirmed_by], from scratch/plan.py),
#         the two manual decisions below, and scratch/suppress_pairs.json (list of [src, dst]; may be empty).
import json, os
G = '/Users/darshan/Desktop/yang/work/graphs/Markor/'
GD = G + 'graph_def.py'
MARK = '# ================================================================== H. UNREACHABLE entries'

dead = json.load(open(G + 'scratch/dead_plan.json'))
manual = {
    'GsTextWatcherAdapter.before': [
        'no_trigger_in_app',
        'no caller in the app or thirdparty source: grep for GsTextWatcherAdapter.before( and GsTextWatcherAdapter::before finds none; the other two factories (on, after) are used',
        'src/main/java/net/gsantner/opoc/wrapper/GsTextWatcherAdapter.java:29', 'SOURCE'],
    'GsTextWatcherAdapter$1.<init>': [
        'no_trigger_in_app',
        'created only inside GsTextWatcherAdapter.before, which has no caller',
        'src/main/java/net/gsantner/opoc/wrapper/GsTextWatcherAdapter.java:29', 'SOURCE'],
}
entries = dict(dead)
for k, v in manual.items():
    assert k not in entries, k
    entries[k] = v
# (S3, sample route 17) plan.py gives a method with no path the default kind; this one is decided by the API level, see graph_def.py _CB_SKIP.
entries['StoragePermissionActivity.onActivityResult'] = [
    'closed_by_api_level',
    'Activity result hook: it runs only after startActivityForResult from this activity; on API 27 GsContextUtils.requestExternalStoragePermission only calls ActivityCompat.requestPermissions (the startActivityForResult calls are in the API 30+ branch)',
    'src/main/java/net/gsantner/markor/activity/StoragePermissionActivity.java:70-73', 'SOURCE']

# Source-line corrections (scratch/ref_fix.json): overloads that were cited to another overload's line (name -> full ref).
for k, ref in json.load(open(G + 'scratch/ref_fix.json')).items():
    assert k in entries, k
    entries[k] = [entries[k][0], entries[k][1], ref, entries[k][3]]
# keyToStringResId(String): the reason is rewritten; the app's only call (GsPreferenceFragmentBase.java:320) passes a Preference
entries['GsPreferenceFragmentBase.keyToStringResId(String)'] = [
    'no_trigger_in_app',
    'no caller of this String overload: the app\'s only call to keyToStringResId (GsPreferenceFragmentBase.java:320) passes a Preference and binds to keyToStringResId(Preference) at line 215; no method reference and no XML handler uses this overload (the library ancestors do not declare a method of this name)',
    'src/main/java/net/gsantner/opoc/frontend/base/GsPreferenceFragmentBase.java:226', 'SOURCE']

pairs = json.load(open(G + 'scratch/suppress_pairs.json')) if os.path.exists(G + 'scratch/suppress_pairs.json') else []

lines = [MARK + ' (generated by scratch/emit_unreach.py)',
         '# Each entry: method -> (kind, reason, source_ref, confirmed_by). Source of truth: scratch/dead_plan.json plus the manual decisions in emit_unreach.py.',
         'UNREACHABLE = {']
for k in sorted(entries):
    kind, reason, ref, conf = entries[k]
    lines.append('    %r: (%r, %r, %r, %r),' % (k, kind, reason, ref, conf))
lines.append('}')
lines.append('')
lines.append('# SUPPRESS: AUTO calls dropped from the graph (src, dst) because they start in unreachable code or call a closed component.')
lines.append('sup(*[%s])' % (', '.join('(%r, %r)' % (a, b) for a, b in sorted(map(tuple, pairs)))))
lines.append('')

src = open(GD, encoding='utf-8').read()
if MARK in src:
    src = src[:src.index(MARK)]
src = src.rstrip('\n') + '\n\n\n' + '\n'.join(lines) + '\n'
open(GD, 'w', encoding='utf-8').write(src)
print('wrote section H: UNREACHABLE entries', len(entries), 'suppress pairs', len(pairs))
