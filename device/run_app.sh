#!/usr/bin/env bash
# Route replay runner (brief D4). Run from the repo root:
#   bash device/run_app.sh <App> <glob> <outdir> [--dry-run]
#   <glob> selects route scripts, e.g. "route_*.py" (matched against the
#   script basename in device/routes/<App>/).
#
# Real mode (default): waits for the device, roots it, installs the
# instrumented APK WITHOUT -g (each route grants only its own
# permissions, unlike the work-emulator tool runner), then per route:
#   (1) pm clear; (2) setup.py (if present) + per-route setup
#   setup_<route>.py (if present, generates run-time files into
#   <outdir>/gen/<route>/); (3) ROUTES.csv fixtures and grants;
#   (4) one coverage dump, discarded; (5) route script with a
#   10-minute timeout; (6) final coverage dump; (7) JaCoCo report
#   for that dump (--classfiles from $WEMU ci/app_env.py CLASSES);
#   (8) device/jacoco_lookup.py maps the target method in the report.
# Fixture entries (ROUTES.csv, semicolon-separated) come in three
# forms, mirroring device/drycheck.py:
#   <wemu-relative>            $WEMU/fixtures/<path> -> /sdcard/<path>
#   <repo-relative> -> <dst>   $ROOT/<repo-relative> -> <dst> (text
#                              fixtures committed under
#                              device/routes/<App>/, conventionally
#                              device/routes/<App>/fixtures/)
#   gen:<name> -> <dst>        <outdir>/gen/<route>/<name> -> <dst>
#                              (generated by setup_<route>.py at run
#                              time; never committed — generated files
#                              live only under <outdir>)
# Route scripts run with GEN_DIR=<outdir>/gen/<route> in the
# environment, so a script that pushes a generated file can prefer
# $GEN_DIR/<file> (falling back to its beside-script path).
# Writes <outdir>/results.csv (columns: app,route,method,edges,reached,
# script_status,steps_done,steps_total,error,run_id), per-route steps
# logs, screens/route_NN/ and logcat/route_NN.txt evidence.
#   reached = yes | no | not_run; script_status = ok | failed_at_step_N
#   | timeout | unscriptable. Coverage truth is reported even when the
#   script failed or timed out; a missing/invalid final dump gives
#   reached=not_run with error=coverage_missing. A lookup of "absent"
#   gives reached=no with error=method_absent_in_report.
#   failed_at_step_0 = setup, per-route setup, or fixture phase;
#   failed_at_step_1 after steps_done=0 also covers a dry-plan
#   failure (see below).
# Dry-run mode (--dry-run): no adb at all. Runs device/drycheck.py
# --load-scripts, which writes <outdir>/dryrun_report.txt (one line per
# route, PASS or FAIL with reason, plus "<App>: N PASS, M FAIL").
#
# Environment: WEMU (work-emulator checkout, required); RUN_ID (default
# local-<UTC timestamp>); JACOCO_JAR (default $WEMU/.cache/jacococli.jar,
# fetched via $WEMU/ci/get_jacoco.sh when missing).
set -u

APP="${1:-}"; GLOB="${2:-}"; OUTDIR="${3:-}"; DRY=0
if [ "${4:-}" = "--dry-run" ]; then DRY=1; fi
if [ -z "$APP" ] || [ -z "$GLOB" ] || [ -z "$OUTDIR" ]; then
  echo "usage: run_app.sh <App> <glob> <outdir> [--dry-run]" >&2; exit 2
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$SCRIPT_DIR")"
DEVICE_DIR="$SCRIPT_DIR"
WEMU="${WEMU:-}"
if [ -z "$WEMU" ]; then echo "run_app.sh: \$WEMU is not set" >&2; exit 2; fi
RUN_ID="${RUN_ID:-local-$(date -u +%Y%m%dT%H%M%SZ)}"

log() { echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) $*" | tee -a "$OUTDIR/run.log"; }

mkdir -p "$OUTDIR"
: > "$OUTDIR/run.log"

if [ "$DRY" = 1 ]; then
  log "dry run for $APP (no adb)"
  python3 -I "$DEVICE_DIR/drycheck.py" "$APP" --root "$ROOT" --wemu "$WEMU" \
    --out "$OUTDIR" --load-scripts
  exit $?
fi

# --- real mode: app environment from work-emulator -------------------
eval "$(cd "$WEMU" && python3 ci/app_env.py "$APP")"  # sets PKG RECEIVER APK CLASSES
APK_ABS="$WEMU/$APK"
JACOCO_JAR="${JACOCO_JAR:-$WEMU/.cache/jacococli.jar}"
if [ ! -f "$JACOCO_JAR" ]; then
  log "fetching JaCoCo CLI via $WEMU/ci/get_jacoco.sh"
  (cd "$WEMU" && bash ci/get_jacoco.sh) || true
fi
if [ ! -f "$JACOCO_JAR" ]; then echo "run_app.sh: no $JACOCO_JAR" >&2; exit 2; fi
command -v adb >/dev/null 2>&1 || { echo "run_app.sh: adb not found" >&2; exit 2; }

wait_for_device() {
  adb wait-for-device
  local i boot
  for i in $(seq 1 120); do
    boot="$(adb shell getprop sys.boot_completed 2>/dev/null | tr -d '\r')"
    [ "$boot" = "1" ] && break
    sleep 5
  done
}

dump_once() {  # dump_once <outfile> ; 0 when the dump is valid
  local out="$1"
  adb shell am broadcast -a edu.gatech.m3.emma.COLLECT_COVERAGE -n "$PKG/$RECEIVER" >/dev/null 2>&1
  sleep 2
  rm -f "$out"
  if ! adb pull "/data/data/$PKG/files/coverage.ec" "$out" >/dev/null 2>&1; then
    adb shell run-as "$PKG" cat files/coverage.ec > "$out" 2>/dev/null || true
  fi
  [ -s "$out" ] || return 1
  local magic size
  magic="$(od -An -tx1 -N3 "$out" | tr -d ' \n')"
  size="$(wc -c < "$out" | tr -d ' ')"
  [ "$magic" = "01c0c0" ] && [ "$size" -gt 5 ]
}

jacoco_report() {  # jacoco_report <ec> <xml>
  local ec="$1" xml="$2" args=() c
  for c in $CLASSES; do args+=(--classfiles "$WEMU/$c"); done
  java -jar "$JACOCO_JAR" report "$ec" "${args[@]}" --xml "$xml" >/dev/null 2>&1
}

csv_escape() { echo "$1" | tr ',' ';' | tr '\n' ' ' | tr '\t' ' '; }

# resolve_fixture <entry> ; prints "<src>|<dst>" on stdout, 0 on success.
# Fixture entry forms (mirror device/drycheck.py parse_fixture_entry):
#   <wemu-relative>            $WEMU/fixtures/<path> -> /sdcard/<path>
#   <repo-relative> -> <dst>   $ROOT/<repo-relative> -> <dst>
#   gen:<name> -> <dst>        $OUTDIR/gen/<route>/<name> -> <dst>
# Uses globals ROOT, WEMU, OUTDIR, route. Returns 1 (message on
# stderr) for any form that is not one of the three. A repo source
# outside device/routes/<App>/ is rejected: route text fixtures
# live under the app's routes dir, never elsewhere in the repo.
resolve_fixture() {
  local entry="$1" src dst rest gname gdst fsrc0
  case "$entry" in
    gen:*)
      rest="${entry#gen:}"; rest="$(echo "$rest" | sed 's/^ *//;s/ *$//')"
      gname="${rest%% -> *}"; gdst="${rest#* -> }"
      gname="$(echo "$gname" | sed 's/^ *//;s/ *$//')"; gdst="$(echo "$gdst" | sed 's/^ *//;s/ *$//')"
      if [ "$gname" = "$rest" ] || [ -z "$gname" ] || [ -z "$gdst" ]; then
        echo "bad generated fixture entry: $entry" >&2; return 1
      fi
      echo "$OUTDIR/gen/$route/$gname|$gdst" ;;
    *" -> "*)
      fsrc0="${entry%% -> *}"; dst="${entry#* -> }"
      fsrc0="$(echo "$fsrc0" | sed 's/^ *//;s/ *$//')"; dst="$(echo "$dst" | sed 's/^ *//;s/ *$//')"
      if [ -z "$fsrc0" ] || [ -z "$dst" ]; then
        echo "fixture entry needs src and dst: $entry" >&2; return 1
      fi
      case "$fsrc0" in
        device/routes/"$APP"/*) echo "$ROOT/$fsrc0|$dst" ;;
        device/*)
          echo "fixture source outside app routes dir: $entry" >&2; return 1 ;;
        *) echo "$WEMU/fixtures/$fsrc0|$dst" ;;
      esac ;;
    *)
      echo "$WEMU/fixtures/$entry|/sdcard/$entry" ;;
  esac
}

wait_for_device
adb root >/dev/null 2>&1 || true
adb wait-for-device
log "installing $APK_ABS WITHOUT -g"
adb install -r -t "$APK_ABS" || { echo "run_app.sh: install failed" >&2; exit 1; }

mkdir -p "$OUTDIR/steps" "$OUTDIR/steps_dry" "$OUTDIR/screens" \
  "$OUTDIR/logcat" "$OUTDIR/dumps" "$OUTDIR/coverage"
echo "app,route,method,edges,reached,script_status,steps_done,steps_total,error,run_id" > "$OUTDIR/results.csv"

ROUTES_DIR="$ROOT/device/routes/$APP"
python3 -I "$DEVICE_DIR/route_info.py" "$APP" --all --root "$ROOT" > "$OUTDIR/.routes.tsv" || {
  echo "run_app.sh: cannot read ROUTES.csv for $APP" >&2; exit 1; }

# Throwaway SSH server (WITH_SSH_SERVER=1): a per-run sshd on the
# CI host for routes that need a live SSH server (e.g. Amaze SFTP
# routes). The emulator reaches the host at 10.0.2.2, so the server
# listens on 127.0.0.1:$SSH_PORT (default 2222, a high port — no
# privilege needed to bind it). Both keys are generated at run time
# with no passphrase and live only under <outdir> (never committed,
# never logged): a host key, and a client keypair whose public half
# is the only authorized key. Route scripts that need the client
# key read it from $OUTDIR/ssh_client_key via their --outdir
# argument and push it to the device themselves. Password auth is
# off; only the per-run client key can log in, as the CI user
# (sshd as non-root serves only the current user). If sshd or
# ssh-keygen is missing, or the server fails to start, the run
# exits 2 immediately with a provisioning message — it never runs
# SSH routes without a server and fails them confusingly. SMB is
# NOT supported this way: smbd needs root (ports 139/445 plus user
# management), so routes needing a live SMB host stay unscriptable
# with that precise reason; no user-space SMB server is faked here.
# The server is killed on exit (trap) so no per-run server outlives
# the run.
cleanup_ssh_server() {
  if [ -n "${SSHD_PID:-}" ] && kill -0 "$SSHD_PID" 2>/dev/null; then
    kill "$SSHD_PID" 2>/dev/null || true
    wait "$SSHD_PID" 2>/dev/null || true
  fi
}
if [ "${WITH_SSH_SERVER:-0}" = 1 ]; then
  command -v sshd >/dev/null 2>&1 || { echo "run_app.sh: WITH_SSH_SERVER=1 but sshd not found on the runner" >&2; exit 2; }
  command -v ssh-keygen >/dev/null 2>&1 || { echo "run_app.sh: WITH_SSH_SERVER=1 but ssh-keygen not found on the runner" >&2; exit 2; }
  SSH_PORT="${SSH_PORT:-2222}"
  export SSH_PORT
  # The app must log in as the CI user; scripts read SSH_USER from
  # the environment (same pattern as TOUCH_DEVICE below) instead
  # of hardcoding a username that varies per runner image.
  SSH_USER="$(whoami)"
  export SSH_USER
  ssh-keygen -t ed25519 -f "$OUTDIR/ssh_host_key" -N '' -C "device-replay-host" >/dev/null 2>&1 || { echo "run_app.sh: per-run host key generation failed" >&2; exit 2; }
  ssh-keygen -t ed25519 -f "$OUTDIR/ssh_client_key" -N '' -C "device-replay-client" >/dev/null 2>&1 || { echo "run_app.sh: per-run client key generation failed" >&2; exit 2; }
  cp "$OUTDIR/ssh_client_key.pub" "$OUTDIR/authorized_keys"
  chmod 600 "$OUTDIR/ssh_host_key" "$OUTDIR/ssh_client_key" "$OUTDIR/authorized_keys"
  sshd -D -p "$SSH_PORT" -h "$OUTDIR/ssh_host_key" \
    -o ListenAddress=127.0.0.1 -o PidFile="$OUTDIR/sshd.pid" \
    -o StrictModes=no -o PasswordAuthentication=no \
    -o PubkeyAuthentication=yes \
    -o AuthorizedKeysFile="$OUTDIR/authorized_keys" \
    >>"$OUTDIR/run.log" 2>&1 &
  SSHD_PID=$!
  trap cleanup_ssh_server EXIT
  sleep 2
  if ! kill -0 "$SSHD_PID" 2>/dev/null; then
    echo "run_app.sh: throwaway sshd failed to start (see run.log)" >&2; exit 2
  fi
  log "throwaway sshd on 127.0.0.1:$SSH_PORT (emulator: 10.0.2.2:$SSH_PORT); per-run keys under outdir"
fi

# Touchscreen node for sendevent multi-touch: route scripts read
# $TOUCH_DEVICE (defaulting to /dev/input/event0 when unset).
# Discovered once per run from `getevent -i` (the device whose ABS
# set has MT POSITION_X/Y, via device/touch_device.py). If
# discovery fails (getevent unavailable, or no MT device), scripts
# fall back to the default node and a gesture on a wrong node
# yields unclear, never wrong — the JaCoCo result decides.
TOUCH_DEVICE="$(adb shell getevent -i 2>/dev/null | python3 -I "$DEVICE_DIR/touch_device.py" 2>/dev/null || true)"
if [ -n "$TOUCH_DEVICE" ]; then
  export TOUCH_DEVICE
  log "touchscreen node: $TOUCH_DEVICE"
else
  log "touchscreen node discovery failed; scripts fall back to /dev/input/event0"
fi

while IFS="$(printf '\t')" read -r route method edges perms fixtures setup status; do
  [ -z "$route" ] && continue
  if [[ "$status" == unscriptable* ]]; then
    reason="${status#unscriptable:}"
    echo "$APP,$route,$method,$edges,not_run,unscriptable,0,0,$(csv_escape "$reason"),$RUN_ID" >> "$OUTDIR/results.csv"
    log "$route unscriptable: $reason"
    continue
  fi
  script="$ROUTES_DIR/$route.py"
  base="$(basename "$script")"
  case "$base" in
    $GLOB) ;;
    *) log "$route skipped (outside glob $GLOB)"; continue ;;
  esac
  if [ ! -f "$script" ]; then
    echo "$APP,$route,$method,$edges,not_run,failed_at_step_1,0,0,missing_script,$RUN_ID" >> "$OUTDIR/results.csv"
    log "$route missing script"
    continue
  fi
  # Dry plan first: steps_total = planned action lines.
  mkdir -p "$OUTDIR/gen/$route"
  if ! GEN_DIR="$OUTDIR/gen/$route" python3 -I "$script" --package "$PKG" --log "$OUTDIR/steps_dry/$route.log" \
      --outdir "$OUTDIR" --dry-run >>"$OUTDIR/run.log" 2>&1 < /dev/null; then
    echo "$APP,$route,$method,$edges,no,failed_at_step_1,0,0,dry_run_failed,$RUN_ID" >> "$OUTDIR/results.csv"
    log "$route dry plan failed"
    continue
  fi
  steps_total="$(wc -l < "$OUTDIR/steps_dry/$route.log" | tr -d ' ')"
  adb shell pm clear "$PKG" >/dev/null 2>&1
  # Setup (per-app setup.py, if the merger shipped one): once per route.
  if [ -f "$ROUTES_DIR/setup.py" ]; then
    if ! python3 -I "$ROUTES_DIR/setup.py" --package "$PKG" \
        --log "$OUTDIR/steps/$route.setup.log" --outdir "$OUTDIR" \
        >>"$OUTDIR/run.log" 2>&1 < /dev/null; then
      echo "$APP,$route,$method,$edges,no,failed_at_step_0,0,$steps_total,setup_failed,$RUN_ID" >> "$OUTDIR/results.csv"
      log "$route setup failed"
      continue
    fi
  fi
  # Per-route setup (generates run-time files, e.g. zips built with
  # python zipfile, or a system font copy): if
  # device/routes/<App>/setup_<route>.py exists, run it; it writes
  # generated files into $OUTDIR/gen/<route>/, which the fixture
  # phase below pushes for gen: entries. Nothing generated here is
  # ever committed (it lives only under <outdir>).
  if [ -f "$ROUTES_DIR/setup_$route.py" ]; then
    mkdir -p "$OUTDIR/gen/$route"
    if ! GEN_DIR="$OUTDIR/gen/$route" python3 -I "$ROUTES_DIR/setup_$route.py" --package "$PKG" \
        --log "$OUTDIR/steps/$route.gensetup.log" --outdir "$OUTDIR" \
        --gen-dir "$OUTDIR/gen/$route" \
        >>"$OUTDIR/run.log" 2>&1 < /dev/null; then
      echo "$APP,$route,$method,$edges,no,failed_at_step_0,0,$steps_total,setup_failed,$RUN_ID" >> "$OUTDIR/results.csv"
      log "$route per-route setup failed"
      continue
    fi
  fi
  # Fixtures + media scan, then per-route permission grants.
  # Entry forms mirror device/drycheck.py (see the header comment).
  fixture_failed=0
  if [ -n "$fixtures" ]; then
    oldifs="$IFS"; IFS=';'
    for fix in $fixtures; do
      fix="$(echo "$fix" | sed 's/^ *//;s/ *$//')"
      [ -z "$fix" ] && continue
      if ! resolved="$(resolve_fixture "$fix" 2>&1)"; then
        fixture_failed=1; log "$route $resolved"; break
      fi
      fsrc="${resolved%%|*}"; fdst="${resolved#*|}"
      if [ ! -f "$fsrc" ]; then
        fixture_failed=1; log "$route fixture source missing: $fsrc (entry: $fix)"; break
      fi
      if ! adb push "$fsrc" "$fdst" >>"$OUTDIR/run.log" 2>&1; then
        fixture_failed=1; log "$route fixture push failed: $fix"; break
      fi
      dst_rel="${fdst#/sdcard/}"
      case "$dst_rel" in
        Music/*|Pictures/*)
          adb shell am broadcast -a android.intent.action.MEDIA_SCANNER_SCAN_FILE \
            -d "file://$fdst" >/dev/null 2>&1 || true ;;
      esac
    done
    IFS="$oldifs"
  fi
  if [ "$fixture_failed" = 1 ]; then
    echo "$APP,$route,$method,$edges,no,failed_at_step_0,0,$steps_total,fixture_push_failed,$RUN_ID" >> "$OUTDIR/results.csv"
    continue
  fi
  # Grants, with one exception: permission-dialog routes (method
  # onRequestPermissionsResult) must NOT be pre-granted. Their edges
  # include the permission dialog itself (a "not granted yet"
  # request edge, then a dialog-answer edge), and pre-granting would
  # prevent the dialog from appearing, so the route could never
  # fire. The script drives the dialog (Allow/Deny) instead. This
  # covers Diary route_17, Vanilla-Music route_26, and any future
  # analog; the skip is logged in run.log.
  case "$method" in
    *onRequestPermissionsResult*)
      log "$route permission-dialog route: pre-grants skipped" ;;
    *)
  if [ -n "$perms" ]; then
    oldifs="$IFS"; IFS=';'
    for perm in $perms; do
      perm="$(echo "$perm" | sed 's/^ *//;s/ *$//')"
      [ -z "$perm" ] && continue
      adb shell pm grant "$PKG" "$perm" >>"$OUTDIR/run.log" 2>&1 || \
        log "$route grant failed (continuing): $perm"
    done
    IFS="$oldifs"
  fi
      ;;
  esac
  # Discard dump (receiver resets counters), then the real run.
  dump_once "$OUTDIR/coverage/$route.discard.ec" || true
  rm -f "$OUTDIR/coverage/$route.discard.ec"
  GEN_DIR="$OUTDIR/gen/$route" timeout 600 python3 -I "$script" --package "$PKG" --log "$OUTDIR/steps/$route.log" \
    --outdir "$OUTDIR" --adb adb >>"$OUTDIR/run.log" 2>&1 < /dev/null
  rc=$?
  if [ -f "$OUTDIR/steps/$route.log" ]; then
    steps_done="$(wc -l < "$OUTDIR/steps/$route.log" | tr -d ' ')"
  else
    steps_done=0
  fi
  if [ "$rc" = 124 ]; then script_status="timeout";
  elif [ "$rc" = 0 ]; then script_status="ok";
  else script_status="failed_at_step_$((steps_done + 1))"; fi
  adb logcat -d > "$OUTDIR/logcat/$route.txt" 2>/dev/null || true
  adb logcat -c >/dev/null 2>&1 || true
  # Final dump + JaCoCo report + method lookup.
  reached="not_run"; error="coverage_missing"
  if dump_once "$OUTDIR/coverage/$route.ec"; then
    if jacoco_report "$OUTDIR/coverage/$route.ec" "$OUTDIR/coverage/$route.xml"; then
      hit="$(python3 -I "$DEVICE_DIR/jacoco_lookup.py" \
        "$ROOT/graphs/$APP/method_list.json" "$OUTDIR/coverage/$route.xml" \
        "$method" --tools "$ROOT/tools" 2>/dev/null || echo absent)"
      case "$hit" in
        reached) reached="yes"; error="" ;;
        not_reached) reached="no"; error="" ;;
        *) reached="no"; error="method_absent_in_report" ;;
      esac
    else
      error="jacoco_report_failed"
    fi
  fi
  echo "$APP,$route,$method,$edges,$reached,$script_status,$steps_done,$steps_total,$(csv_escape "$error"),$RUN_ID" >> "$OUTDIR/results.csv"
  log "$route $script_status reached=$reached steps=$steps_done/$steps_total $error"
done < "$OUTDIR/.routes.tsv"
rm -f "$OUTDIR/.routes.tsv"
log "done $APP; results in $OUTDIR/results.csv"
