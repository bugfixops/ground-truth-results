import argparse
import os
import sys

# Repo-root derivation (verified form): _HERE is this file's directory
# (device/routes/openlauncher); three dirname steps up from _HERE give
# routes -> device -> repo root. Three dirname calls on __file__
# itself would land on device/ and break `from device.harness import`.
_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(_HERE)))
sys.path.insert(0, _REPO_ROOT)

from device.harness import Runner  # noqa: E402

EDGE_IDS = [
    "E3a1527b1", "E996c92b8", "E5aa97973", "E8b7dd43a", "E23660de0",
    "E1701006d", "Ecded7dff", "E06eb37f4", "E823bd16a", "E0117cced",
    "E9629945d", "E506c5f2f", "E39f55ef0", "E3d08f3e9", "Eaf05406d",
]

PKG_COMPONENT = "com.benny.openlauncher/com.benny.openlauncher.activity.Init"

# Intent.EXTRA_SHORTCUT_NAME's constant value, used as the broadcast
# extra key (ShortcutReceiver reads it at util/ShortcutReceiver.java:27).
EXTRA_SHORTCUT_NAME = "android.intent.extra.shortcut.NAME"


def main(argv=None):
    parser = argparse.ArgumentParser(description="openlauncher route_15")
    parser.add_argument("--package", required=True)
    parser.add_argument("--log", required=True)
    parser.add_argument("--outdir", required=True)
    parser.add_argument("--adb", default="adb")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    r = Runner(package=args.package, route="route_15", edge_ids=EDGE_IDS,
               log_path=args.log, dry_run=args.dry_run, adb=args.adb,
               outdir=args.outdir)

    # E3a1527b1 -- Tap the OpenLauncher icon in another launcher
    # (MAIN + LAUNCHER filter), or adb monkey / am start.
    # The launcher entry activity is Init (AndroidManifest.xml:28-36).
    r.launch(PKG_COMPONENT, edge="E3a1527b1")
    # E996c92b8 -- The system instantiates Init, then calls onCreate.
    r.comment("lifecycle: system instantiates Init, then calls onCreate",
              edge="E996c92b8")
    # E5aa97973 -- First start: the three onboarding pages are set up.
    # Guard: getBoolean("firstStart", true) is true (default on fresh
    # install, i.e. after run_app.sh pm clear).
    r.comment("lifecycle: first-start onboarding pages set up",
              edge="E5aa97973")
    # E8b7dd43a -- Tap "Skip".
    # Init.java sets the skip button title from intro_skip
    # (res/values/strings.xml: intro_skip = "Skip"); the button itself
    # is generated by the Onboarder library, so text is the only
    # selector available from these inputs.
    r.tap(edge="E8b7dd43a", text="Skip")
    # E23660de0 -- Direct call: onSkipButtonPressed -> RockIt.
    r.comment("direct call: onSkipButtonPressed -> RockIt",
              edge="E23660de0")
    # E1701006d -- startActivity(new Intent(Init.this, Home.class))
    # then finish().
    r.comment("framework: RockIt starts Home, then finishes Init",
              edge="E1701006d")
    # Ecded7dff -- The system instantiates Home, then calls onCreate.
    r.comment("lifecycle: system instantiates Home, then calls onCreate",
              edge="Ecded7dff")
    # E06eb37f4 -- onStart after onCreate.
    r.comment("lifecycle: Home.onStart after onCreate", edge="E06eb37f4")
    # E823bd16a -- onResume after onStart.
    r.comment("lifecycle: Home.onResume after onStart", edge="E823bd16a")
    # E0117cced -- handleLauncherPause() at the first resume: desktop
    # is not in edit mode and the drawer is not visible.
    r.comment("lifecycle: handleLauncherPause at first resume",
              edge="E0117cced")
    # E9629945d -- groupPopup.dismissPopup(). Guard: groupPopup != null.
    r.comment("framework: groupPopup.dismissPopup()", edge="E9629945d")
    # E506c5f2f -- the popup is hidden; home desktop state reached.
    # Home is now foreground, so its runtime-registered shortcut
    # receiver (Home.java:642) is live for the next edge.
    r.comment("framework: popup hidden, home desktop reached, shortcut "
              "receiver registered",
              edge="E506c5f2f")
    # E39f55ef0 -- In another app: "add to home screen" (legacy
    # shortcut). Trigger: an app sends the legacy INSTALL_SHORTCUT
    # broadcast (activity/Home.java:176-177).
    # FLAG (see REPORT.md): adb broadcast can carry string extras
    # only, so the nested Intent extra (EXTRA_SHORTCUT_INTENT) and
    # the Bitmap icon extra cannot be sent this way. The receiver
    # still reaches the target: ShortcutReceiver.onReceive proceeds
    # with a null shortcut intent, drawableToBitmap(null) returns
    # null (util/Tool.java:281-282), and saveIconAndReturnID catches
    # the resulting exception around bitmap.compress
    # (util/Tool.java:262-270) after having been called from
    # widget/Desktop.java:725 -- before the null-intent putExtra at
    # Desktop.java:726, which is past the target. The shortcut item
    # itself therefore does not complete cleanly on a real run.
    r.broadcast(edge="E39f55ef0",
                action="com.android.launcher.action.INSTALL_SHORTCUT",
                extras={EXTRA_SHORTCUT_NAME: "OpenLauncherTest"})
    # E3d08f3e9 -- Direct call: ShortcutReceiver.onReceive ->
    # Desktop.Item.newShortcutItem(Context, String, Intent, Bitmap)
    # (util/ShortcutReceiver.java:52).
    r.comment("direct call: ShortcutReceiver.onReceive -> "
              "Desktop.Item.newShortcutItem",
              edge="E3d08f3e9")
    # Eaf05406d -- Direct call: newShortcutItem ->
    # Tool.saveIconAndReturnID (widget/Desktop.java:725). This edge
    # reaches the target.
    r.comment("direct call: newShortcutItem -> Tool.saveIconAndReturnID "
              "(target)",
              edge="Eaf05406d")

    r.done()
    return 0


if __name__ == "__main__":
    sys.exit(main())
