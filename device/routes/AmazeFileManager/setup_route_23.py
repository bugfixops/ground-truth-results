#!/usr/bin/env python3
"""Per-route setup for AmazeFileManager route_23 (SSH row + bad key).

Copies the per-run SSH client key (generated by run_app.sh under
WITH_SSH_SERVER=1, never committed) into this route's gen dir
as device_replay_key, so run_app.sh's fixture phase pushes it to
/sdcard/Download/device_replay_key (see the ROUTES.csv fixtures
cell: gen:device_replay_key -> /sdcard/Download/device_replay_key)
before the route script runs. The route script then picks that
valid key to create the saved SSH row (the route_23
precondition), and later picks the repo fixture
amaze_bad_key.txt to reach the parse-error path.

This script itself pushes nothing to the device; it only copies
a host file into the gen dir. It fails loudly (exit 1) when the
key is absent — i.e. when the run was started without
WITH_SSH_SERVER=1 — so the route fails at setup (unclear, never
wrong) instead of running without a server. The bad-key fixture
needs no setup step: it is a committed repo file that run_app.sh
pushes from device/routes/AmazeFileManager/amaze_bad_key.txt.

Interface (same as every per-route setup script): --package,
--log, --outdir, --gen-dir. The key lives directly under
--outdir (run_app.sh writes $OUTDIR/ssh_client_key); the gen
dir is --gen-dir.
"""

import argparse
import os
import shutil
import sys


def main():
    ap = argparse.ArgumentParser(
        description="Stage the per-run SSH client key for Amaze route_23.")
    ap.add_argument('--package', required=True)
    ap.add_argument('--log', required=True)
    ap.add_argument('--outdir', required=True)
    ap.add_argument('--gen-dir', required=True)
    a = ap.parse_args()
    src = os.path.join(a.outdir, 'ssh_client_key')
    if not os.path.isfile(src):
        print("setup_route_23: %s not found; run with WITH_SSH_SERVER=1 "
              "so run_app.sh generates the per-run client key"
              % src, file=sys.stderr)
        return 1
    os.makedirs(a.gen_dir, exist_ok=True)
    dst = os.path.join(a.gen_dir, 'device_replay_key')
    shutil.copyfile(src, dst)
    with open(a.log, 'a', encoding='utf-8') as f:
        f.write("copied %s -> %s (%d bytes)\n"
                % (src, dst, os.path.getsize(dst)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
